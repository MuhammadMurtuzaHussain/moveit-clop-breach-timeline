#!/usr/bin/env node
/**
 * Regenerates docs/sources.md and docs/timeline.md from assets/js/timeline-data.js
 * so the printable docs can never drift from the diagram. Run `npm run docs`
 * after editing the data file, and commit the result.
 */
const fs = require("fs");
const path = require("path");
const { PHASES, SOURCES, EVENTS, MITRE } = require("../assets/js/timeline-data.js");

const docsDir = path.join(__dirname, "..", "docs");
const byId = Object.fromEntries(SOURCES.map((s, i) => [s.id, { ...s, num: i + 1 }]));
const phaseLabel = Object.fromEntries(PHASES.map((p) => [p.id, p.label]));

function cite(ids) {
  return ids.map((id) => `[${byId[id].num}]`).join("");
}

// ---- docs/sources.md ----------------------------------------------------
let sourcesMd = `# Sources\n\n`;
sourcesMd += `Bibliography for the MOVEit / Cl0p breach timeline (\`assets/js/timeline-data.js\`). `;
sourcesMd += `Generated by \`scripts/build-docs.js\` — edit the data file, not this one.\n\n`;
SOURCES.forEach((s, i) => {
  sourcesMd += `**[${i + 1}] ${s.authors}.** "${s.title}." *${s.publication}*, ${s.date}. ${s.url}\n`;
  if (s.note) sourcesMd += `> ${s.note}\n`;
  sourcesMd += `\n`;
});

// ---- docs/timeline.md ----------------------------------------------------
let timelineMd = `# Timeline: the MOVEit Transfer / Cl0p mass-exploitation campaign\n\n`;
timelineMd += `Plain-text mirror of \`index.html\`, generated from \`assets/js/timeline-data.js\`. `;
timelineMd += `See [sources.md](sources.md) for the numbered bibliography and [mitre-attck-mapping.md](mitre-attck-mapping.md) for the ATT&CK mapping.\n\n`;

let currentPhase = null;
for (const e of EVENTS) {
  if (e.phase !== currentPhase) {
    currentPhase = e.phase;
    timelineMd += `\n## ${phaseLabel[currentPhase]}\n\n`;
  }
  const cves = e.cveIds && e.cveIds.length ? ` (${e.cveIds.join(", ")})` : "";
  timelineMd += `**${e.date} — ${e.title}${cves}** ${cite(e.citations)}\n\n${e.summary}\n\n`;
}

// ---- docs/mitre-attck-mapping.md -----------------------------------------
let mitreMd = `# MITRE ATT&CK mapping\n\n`;
mitreMd += `How the MOVEit/Cl0p campaign maps onto MITRE ATT&CK for Enterprise. `;
mitreMd += `Generated by \`scripts/build-docs.js\` from \`assets/js/timeline-data.js\`.\n\n`;
mitreMd += `| Tactic | Technique | Evidence in this campaign | Source |\n`;
mitreMd += `|---|---|---|---|\n`;
for (const m of MITRE) {
  mitreMd += `| ${m.tactic} | ${m.technique} | ${m.note} | ${cite(m.citations)} |\n`;
}

fs.writeFileSync(path.join(docsDir, "sources.md"), sourcesMd);
fs.writeFileSync(path.join(docsDir, "timeline.md"), timelineMd);
fs.writeFileSync(path.join(docsDir, "mitre-attck-mapping.md"), mitreMd);

console.log("✓ Regenerated docs/sources.md, docs/timeline.md and docs/mitre-attck-mapping.md");
